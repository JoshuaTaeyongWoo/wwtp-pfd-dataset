"""
s07_dedup_catalog.py — merge all per-source provenance files into one catalog, remove duplicates, report stats.

  * exact duplicates: identical sha256
  * near duplicates : perceptual hash (pHash, 64 bit) Hamming distance <= PHASH_T  (same figure re-used in
                      two papers, page render vs embedded image, re-encoded copies)
  * For each duplicate cluster the record with the most permissive tier (A over B) and, within a tier,
    the earliest acquisition is kept as `canonical`; the others are kept in the catalog with
    `duplicate_of` set (nothing is deleted from disk).

Outputs
  data/catalog.csv                full catalog (one row per file)
  data/catalog_canonical.csv      de-duplicated rows only
  data/stats.md                   markdown tables for the methodology write-up

Usage: python s07_dedup_catalog.py
"""
from __future__ import annotations

import json
from collections import Counter, defaultdict
from pathlib import Path

import pandas as pd

from common import DATA, PROV, ROOT, read_jsonl, caption_tier

PHASH_T = 6
TIER_ORDER = {"A": 0, "B": 1}


def hamming(a: str, b: str) -> int:
    return bin(int(a, 16) ^ int(b, 16)).count("1")


def main():
    rows = []
    for f in sorted(PROV.glob("*.jsonl")):
        for r in read_jsonl(f):
            r = dict(r)
            ex = r.pop("extra", {}) or {}
            # re-score captions with the current (v2) rule so the catalog reflects the latest filter without
            # re-downloading; the tier assigned at download time is kept in extra_json as caption_tier_at_download
            r["caption_tier"] = (caption_tier(r["caption"]) or "T0") if r.get("caption") else ex.get("caption_tier")
            r["kind"] = ex.get("kind")
            r["doi"] = ex.get("doi")
            r["extra_json"] = json.dumps(ex, ensure_ascii=False)
            r["exists"] = (ROOT / r["image_path"]).exists()
            rows.append(r)
    df = pd.DataFrame(rows)
    if df.empty:
        print("no provenance records yet")
        return
    df = df[df["exists"]].copy()
    df["image_size"] = df["image_size"].apply(lambda s: tuple(s) if isinstance(s, list) else s)

    # ---- exact duplicates
    df["duplicate_of"] = None
    df = df.sort_values(["tier", "acquired_at"]).reset_index(drop=True)
    first_by_sha = {}
    for i, r in df.iterrows():
        if r["sha256"] in first_by_sha:
            df.at[i, "duplicate_of"] = first_by_sha[r["sha256"]]
        else:
            first_by_sha[r["sha256"]] = r["record_id"]

    # ---- near duplicates (pHash) among non-exact-duplicate rasters; bucketed by hash prefix for speed
    cand = df[df["duplicate_of"].isna() & df["phash"].notna()]
    buckets = defaultdict(list)
    for i, r in cand.iterrows():
        buckets[r["phash"][:2]].append(i)   # same leading byte is a cheap pre-filter; cross-bucket near-dups are rare
    canon_idx = {}
    for idxs in buckets.values():
        kept = []
        for i in idxs:
            h = df.at[i, "phash"]
            match = next((k for k in kept if hamming(h, df.at[k, "phash"]) <= PHASH_T), None)
            if match is None:
                kept.append(i)
            else:
                df.at[i, "duplicate_of"] = df.at[match, "record_id"]
    df["canonical"] = df["duplicate_of"].isna()

    # ---- write catalog
    cols = ["record_id", "canonical", "duplicate_of", "source", "tier", "caption_tier", "kind", "license",
            "image_path", "image_size", "sha256", "phash", "doc_id", "doi", "title", "venue", "year",
            "figure_label", "caption", "rights_holder", "file_url", "landing_url", "acquisition_method",
            "query", "filter_rule", "acquired_at", "extra_json"]
    df[cols].to_csv(DATA / "catalog.csv", index=False, encoding="utf-8-sig")
    can = df[df["canonical"]]
    can[cols].to_csv(DATA / "catalog_canonical.csv", index=False, encoding="utf-8-sig")

    # ---- stats
    lines = ["# Collection statistics", "", f"Generated by s07_dedup_catalog.py; pHash threshold = {PHASH_T} bits.", ""]
    def table(title, g):
        lines.append(f"## {title}")
        lines.append("")
        lines.append(g.to_markdown())
        lines.append("")
    tot = pd.DataFrame({
        "files_downloaded": df.groupby("source").size(),
        "exact_or_near_duplicates": df[~df["canonical"]].groupby("source").size(),
        "canonical_files": can.groupby("source").size(),
        "tier_A_canonical": can[can["tier"] == "A"].groupby("source").size(),
        "tier_B_canonical": can[can["tier"] == "B"].groupby("source").size(),
        "unique_documents": can.groupby("source")["doc_id"].nunique(),
    }).fillna(0).astype(int)
    tot.loc["TOTAL"] = tot.sum()
    table("Per source", tot)
    table("Canonical files by licence", can.groupby(["tier", "license"]).size().rename("n").reset_index().sort_values("n", ascending=False).head(25).set_index(["tier", "license"]))
    lit = can[can["source"].isin(["europepmc_pmc", "openalex_nonpmc"])]
    if not lit.empty:
        table("Literature figures by caption tier (T1 = whole-plant diagram, T2 = treatment-related schematic, T0 = demoted by the v2 rule after download)",
              lit.groupby(["source", "caption_tier"]).size().rename("n").to_frame())
        table("Literature figures: tier x licence tier (canonical)",
              lit.groupby(["caption_tier", "tier"]).size().unstack(fill_value=0))
        table("Literature figures: top journals", lit.groupby("venue").size().sort_values(ascending=False).head(25).rename("n").to_frame())
        yr = lit["year"].dropna().astype(str).str[:4]
        table("Literature figures by year", yr.value_counts().sort_index().rename("n").to_frame().T)
    (DATA / "stats.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
